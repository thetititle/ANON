export function generateMemorialMessage(
  _deceasedName: string,
  personalityTags: string[],
  memorialId: string,
  is49th = false,
  isElder = false,
  isChildElder = false
): string {
  const pool = isChildElder
    ? (is49th ? MESSAGES_49_CHILD_ELDER : MESSAGES_CHILD_ELDER)
    : isElder
    ? (is49th ? MESSAGES_49_HONORIFIC : MESSAGES_HONORIFIC)
    : (is49th ? MESSAGES_49 : MESSAGES)
  const fallback = isChildElder
    ? (is49th ? '이제 갈게.\n걱정하지 말고 잘 지내야 해.\n사랑해.' : '보고 싶어.\n나 잘 지내고 있어.\n사랑해.')
    : isElder
    ? (is49th ? '이제 편히 갈게요. 기억해 주세요.' : '이곳에 와주셔서 고마워요. 항상 기억하고 있을게요.')
    : (is49th ? '이제 편히 가. 기억할게.' : '이곳에 와줘서 고마워. 항상 기억하고 있을게.')
  for (const tag of personalityTags) {
    const messages = pool[tag]
    if (messages) {
      const index = memorialId.charCodeAt(0) % messages.length
      return messages[index]
    }
  }
  return fallback
}
